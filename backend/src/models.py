from pathlib import Path
from typing import Any

from pydantic import BaseModel, Field, model_validator


class RetrievalMetadata(BaseModel):
    """
    Generated by the Vision LLM.
    This is the source of truth for an indexed image.
    """

    title: str
    summary: str

    people: list[str] = Field(default_factory=list)
    objects: list[str] = Field(default_factory=list)
    actions: list[str] = Field(default_factory=list)
    setting: list[str] = Field(default_factory=list)
    clothing: list[str] = Field(default_factory=list)
    emotions: list[str] = Field(default_factory=list)
    concepts: list[str] = Field(default_factory=list)
    keywords: list[str] = Field(default_factory=list)

    possible_search_queries: list[str] = Field(default_factory=list)
    usage_contexts: list[str] = Field(default_factory=list)

    @model_validator(mode="before")
    @classmethod
    def _coerce_strings_to_lists(cls, data: Any) -> Any:
        """LLMs sometimes return a bare string instead of a list."""
        if isinstance(data, dict):
            # Metadata written before the rebrand used "meme_contexts".
            if "meme_contexts" in data and "usage_contexts" not in data:
                data["usage_contexts"] = data.pop("meme_contexts")

            list_fields = {
                "people", "objects", "actions", "setting",
                "clothing", "emotions", "concepts", "keywords",
                "possible_search_queries", "usage_contexts",
            }
            for field in list_fields:
                val = data.get(field)
                if isinstance(val, str):
                    data[field] = [val]
        return data


class ImageRecord(BaseModel):
    """
    Represents one image on disk together with its metadata.
    """

    filename: str

    image_path: Path

    metadata_path: Path

    semantic_path: Path

    user_description: str

    metadata: RetrievalMetadata


class EmbeddingRecord(BaseModel):
    """
    Stored inside Qdrant payload.
    """

    id: str

    filename: str

    semantic_document: str

    metadata: RetrievalMetadata


class SearchResult(BaseModel):
    """
    Returned from a search.
    """

    score: float

    filename: str

    image_path: str

    metadata: RetrievalMetadata